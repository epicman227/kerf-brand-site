// Generates src/seo-content.js from the approved drafts. Not run by the build.
// Usage: node tools/gen-seo.mjs <seo-md-dir> <seo-article-drafts.md>
// City, vs and FAQ pages: docs/seo/*.md in the Kerf repo (#165, #166). Posts: KERA-534 document seo-article-drafts.
import { readFileSync, writeFileSync } from "fs";
const [dir, posts] = process.argv.slice(2);
const section = (md, name) => {
  const m = md.match(new RegExp(`^## ${name}\\s*\\n([\\s\\S]*?)(?=^## |(?![\\s\\S]))`, "m"));
  return m ? m[1].trim() : "";
};
const blocks = (txt) => txt.split(/\n{2,}/).map((s) => s.trim()).filter(Boolean).map((s) => s.startsWith("### ") ? { h: s.slice(4) } : { p: s });
const strip = (b) => b
  .filter((x) => !(x.p && /^On the published page, the questions below/.test(x.p)))
  .map((x) => x.p ? { p: x.p.replace(/\s*This draft has no booking link\.?/g, "").replace(/\s*There is no booking link for a shop that is not already on both\./g, (m) => m) } : x);
const pages = {};
const sets = [
  ["denver-tree-service", "city", "Denver"], ["colorado-springs-tree-removal", "city", "Colorado Springs"], ["aurora-tree-trimming", "city", "Aurora"],
  ["fort-collins-arborist", "city", "Fort Collins"], ["boulder-emergency-tree-service", "city", "Boulder"],
  ["kerf-vs-quoteiq", "vs", "Kerf vs QuoteIQ"], ["kerf-vs-marketing-agency", "vs", "Kerf vs a marketing agency"], ["tree-care-owner-faq", "faq", "Owner FAQ"],
];
const out = [];
for (const [file, kind, label] of sets) {
  const md = readFileSync(`${dir}/${file}.md`, "utf8");
  const slug = file === "tree-care-owner-faq" ? "tree-care-owners-faq" : file;
  out.push({ slug, kind, label, title: section(md, "Title tag"), description: section(md, "Meta description"), h1: section(md, "H1"), body: strip(blocks(section(md, "Page copy"))) });
}
const pmd = readFileSync(posts, "utf8");
const arts = pmd.split(/^## Article \d+\. /m).slice(1);
const slugs = ["storm-damage-quotes", "missed-call-recovery", "review-requests", "slow-season-marketing"];
arts.forEach((a, i) => {
  const h1 = a.split("\n")[0].trim();
  const body = a.replace(/\n---[\s\S]*$/, "");
  const sec = (n) => (body.match(new RegExp(`### ${n}\\n\\n([\\s\\S]*?)(?=\\n### |$)`)) || [])[1].trim();
  // The drafts name unbuilt slugs. Point them at pages that exist in the site draft. Nothing else in the copy changes.
  const fix = (t) => t
    .replace(/, still a draft and not a live URL, is \[([^\]]+)\]\(\/quoteiq\)/, " is [Kerf vs QuoteIQ](kerf-vs-quoteiq.html)")
    .replace(/, still a draft and not a live URL, is \[[^\]]+\]\(\/(missed-call-text|estimate-follow-up)\)/, " is [Questions from tree care owners](tree-care-owners-faq.html)")
    .replace(/, still a draft and not a live URL: \[[^\]]+\]\(\/estimate-follow-up\)/, ": [Questions from tree care owners](tree-care-owners-faq.html)")
    .replace("The page that carries the missed call is [", "What Kerf does after a missed call is answered in [")
    .replace("The after-job drafts sit on the approved follow-up page: [", "What Kerf drafts after a job is answered in [")
    .replace("The page for it is [Questions", "The owner FAQ covers it: [Questions")
    .replace(" There is no launch page yet for the slow-period drafts. This article does not invent one.", " There is no page yet for the slow-period drafts.");
  out.push({ slug: slugs[i], kind: "post", label: h1, title: sec("Title tag"), description: sec("Meta description"), h1, body: blocks(sec("Article")).map((b) => b.p ? { p: fix(b.p) } : b) });
});
writeFileSync("src/seo-content.js", "// GENERATED by tools/gen-seo.mjs from docs/seo (#165, #166) and the KERA-534 article drafts. Edit the source, not this file.\nexport const SEO = " + JSON.stringify(out, null, 1) + ";\n");
console.log(out.map((o) => `${o.slug} ${o.body.length}`).join("\n"));
